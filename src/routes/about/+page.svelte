<h2>Über die Seite</h2>

<p>
	<i>Houses of the green Dragon</i> ist ein Browserspiel über eine mittelalterliche Stadt und die
	Familien, die in ihr leben. Man spielt keine Figur, sondern ein <b>Haus</b>: eine Reihe von
	Menschen, die geboren werden, arbeiten, heiraten und sterben.
</p>

<h3>Die Uhr läuft weiter</h3>

<p>
	Die Welt hat einen eigenen Takt — eine Stunde in der Wirklichkeit ist eine Stunde in Grünau,
	fünfzig davon sind ein Spieljahr. Sie läuft, ob jemand zusieht oder nicht: Während du fort bist,
	arbeiten die Einwohner, bekommen Kinder, wählen ihren Bürgermeister und sterben.
</p>

<p>
	Handeln kostet <b>Aktionspunkte</b>, und die wachsen mit der Zeit nach — nicht schneller, wenn man
	wartet, und nicht langsamer, wenn man selten hereinschaut. Das Spiel ist darauf gebaut, dass man
	einmal am Tag vorbeikommt, nicht darauf, dass man den ganzen Tag bleibt.
</p>

<h3>Der Tod gehört dazu</h3>

<p>
	Deine Figur wird sterben. Das ist keine Strafe für einen Fehler, sondern der Lauf der Dinge: Mit
	den Jahren steigt die Wahrscheinlichkeit, und irgendwann trifft sie zu. Was bleibt, ist, was du
	vorbereitet hast — <b>ein Erbe</b>, ein Haus, Grundstücke, ein guter Ruf bei den Nachbarn.
	Hinterlässt du niemanden, erlischt dein Haus und dein Besitz fällt an die Stadt.
</p>

<p>
	Deshalb steht die Familie im Mittelpunkt und nicht die einzelne Figur. Wer nur für sich sorgt,
	spielt eine Generation lang.
</p>

<h3>Die Stadt gehört niemandem</h3>

<p>
	Bauland ist knapp, Ämter sind es auch. Der Bürgermeister wird gewählt — von allen Erwachsenen,
	Menschen wie Nichtspielern, und gewählt wird der, den man am liebsten mag. Wer Beziehungen pflegt,
	anständig entlohnt und niemanden gegen sich aufbringt, bekommt die Stimmen. Wer im Amt ist, setzt
	Steuern, weist Bauland aus und lässt öffentliche Häuser errichten.
</p>

<h3>Wie es weitergeht</h3>

<p>
	Das Spiel ist <b>in Arbeit</b>. Vieles steht, manches fehlt, und die Welt läuft erst seit kurzem —
	die Stadt ist noch klein, und man sieht ihr an, dass sie am Anfang steht. Wer jetzt anfängt,
	gehört zu den ersten Häusern.
</p>

