<h2>Spielregeln</h2>

<p>
	<i>
		Kurz: Ein Mensch, ein Konto. Sei zu den anderen so, wie du es umgekehrt erwartest. Der Rest
		ergibt sich.
	</i>
</p>

<h3>Ein Mensch, ein Konto</h3>
<p>
	Wer mehrere Konten führt, hat mehrere Stimmen bei einer Wahl, mehrere Häuser auf knappem Bauland
	und Angestellte, die sich selbst gehören. Das ist keine Kleinigkeit, sondern zerstört genau die
	Knappheit, aus der dieses Spiel besteht.
</p>
<p>
	<small>
		Deshalb: <b>ein Konto je Person.</b> Wer eines verliert oder neu anfangen möchte, meldet sich — das
		lässt sich regeln. Wer zwei parallel führt, verliert beide.
	</small>
</p>

<h3>Was du mit anderen tust</h3>
<p>
	In dieser Welt darf man verhandeln, überbieten, sich verweigern und Fehden austragen. Ein harter
	Zug im Spiel ist kein Verstoß, und ein verlorenes Amt ist kein Unrecht — die Stadt gehört
	niemandem allein.
</p>
<p>
	Was <b>nicht</b> geht, betrifft die Menschen und nicht die Figuren: Beleidigungen, Drohungen, Hetze,
	das Ausforschen oder Veröffentlichen persönlicher Daten anderer. Wer die Grenze zwischen Spielfigur
	und Mensch nicht ziehen kann, ist hier falsch.
</p>

<h3>Namen</h3>
<p>
	Du benennst deinen Nickname, dein Haus, deine Kinder und deine Gebäude. Beleidigende, hetzende
	oder verwechslungsträchtige Namen werden geändert, ohne dass es dafür eine Ankündigung braucht.
	Der Nickname sollte kein Klarname sein — er steht für andere sichtbar, und die Stadtchronik können
	auch Gäste lesen.
</p>

<h3>Fehler im Spiel</h3>
<p>
	Findest du einen Fehler, der dir einen unfairen Vorteil verschafft, sag Bescheid, statt ihn
	auszunutzen. Wer einen offensichtlichen Fehler wiederholt ausnutzt, verliert, was dabei
	herausgekommen ist.
</p>

<h3>Was der Betrieb verspricht — und was nicht</h3>
<p>
	Dies ist ein privat betriebenes Spiel ohne Gewinnerzielungsabsicht. Es gibt nichts zu kaufen, und
	es gibt keine Zusage, dass die Welt für immer läuft. Was zugesagt wird: Die Datenbank wird täglich
	gesichert, ein Serverausfall geht nicht zu deinen Lasten — die verpasste Zeit wird übersprungen
	statt nachgeholt, und niemand verliert dabei seine Aktionspunkte —, und wenn die Welt je enden
	sollte, wird es angekündigt und nicht abgeschaltet.
</p>

